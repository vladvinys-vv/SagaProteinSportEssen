import { describe, expect, it } from "vitest";
import { plural, pluralDecimal, pluralWord } from "@/lib/plural";

describe("русские склонения счётчиков", () => {
  it("выбирает форму по последним цифрам", () => {
    expect(plural(1, "запись", "записи", "записей")).toBe("1 запись");
    expect(plural(2, "запись", "записи", "записей")).toBe("2 записи");
    expect(plural(4, "запись", "записи", "записей")).toBe("4 записи");
    expect(plural(5, "запись", "записи", "записей")).toBe("5 записей");
    expect(plural(21, "запись", "записи", "записей")).toBe("21 запись");
    expect(plural(72, "запись", "записи", "записей")).toBe("72 записи");
    expect(plural(11, "запись", "записи", "записей")).toBe("11 записей");
    expect(plural(112, "запись", "записи", "записей")).toBe("112 записей");
    expect(plural(0, "запись", "записи", "записей")).toBe("0 записей");
  });

  it("даёт слово без числа для составных подписей", () => {
    expect(pluralWord(1, "день", "дня", "дней")).toBe("день");
    expect(pluralWord(3, "день", "дня", "дней")).toBe("дня");
    expect(pluralWord(14, "день", "дня", "дней")).toBe("дней");
  });

  it("дробные значения ставит в родительный падеж единственного числа", () => {
    expect(pluralDecimal(1.6, "доза", "дозы", "доз", "дозы")).toBe("1,6 дозы");
    expect(pluralDecimal(2.5, "день", "дня", "дней", "дня")).toBe("2,5 дня");
    expect(pluralDecimal(6, "доза", "дозы", "доз", "дозы")).toBe("6 доз");
    expect(pluralDecimal(1, "доза", "дозы", "доз", "дозы")).toBe("1 доза");
  });
});
